% Example 3.5 
% Generate a data set consisting of two sine waves closely spaced in frequency (235 and 250 Hz) with 
% added white noise in a 128-point array sampled at 1 kHz. The SNR should be −3 dB. Apply a rectangular, 
% Hamming, and Blackman–Harris window to the signal and take the FT. Plot the magnitude spectra 
% (only the relevant points). 

% Solution
% After defining fs and N, generate the data using sig_noise. Also, generate a frequency vec tor for 
% plotting the spectra. Take the magnitude of the FFT output for the signal with no win dow as the 
% rectangular window. Then multiply the signal by a Hamming window generated by MATLAB’s hamming routine. 
% Note that the multiplication should be point by point using MATLAB’s.* operator and the window function, 
% and the signal may need to be transposed to have the same vector orientation. Repeat the analysis using 
% the Blackman–Harris window.
clear all;
close all;
clc;

addpath(genpath("funcoes_auxiliares_and_data_tests"));   % torna sig_noise visível

% Example 3.5 Application of several window functions
%
fs = 1000;                              % Sampling freq assumed by sig_noise
N = 128;
x = sig_noise([235 250],-3,N);          % Generate signal
f = (0:N-1)*fs/N;                       % Frequency vector
%
X_mag = abs(fft(x));                    % Mag. spect: rect. (no) window
subplot(3,1,1);
plot(f(1:N/2),X_mag(1:N/2));            % Plot magnitude
title('Rectangular');
xlabel('Frequency');
ylabel('X(f)');
%
x1 = x .*hamming(N)';                   % Apply Hamming window (Eq. 3.26)
X_mag = abs(fft(x1));                   % Mag. spect: Hamming window
subplot(3,1,2);
plot(f(1:N/2),X_mag(1:N/2),'k');        % Plot magnitude
title('Hamming');
xlabel('Frequency');
ylabel('X(f)');
%
x1 = x .*blackmanharris(N)';            % Apply Blackman-Harris (Eq. 3.27)
X_mag = abs(fft(x1));                   % Mag. spect: Blackman-Harris window
subplot(3,1,3);
plot(f(1:N/2),X_mag(1:N/2),'k');        % Plot magnitude
title('Blackman-Harris');
xlabel('Frequency');
ylabel('X(f)');

% Resultados 
%
% A Figura apresenta três espectros. As diferenças entre os três espectros decorrem da aplicação de 
% janelas (windowing). 
% 
% Os dois picos são claramente visíveis no espectro superior, obtido com o uso de 
% uma função retangular; contudo, no espectro central — que utiliza a janela de Hamming —, os dois picos 
% são dificilmente discerníveis, devido ao lóbulo principal mais largo dessa janela, o qual efetivamente 
% realiza uma média das frequências adjacentes. O efeito dessa fusão de frequências torna-se ainda mais 
% acentuado com a utilização da janela de Blackman-Harris, na qual apenas um único pico largo pode ser 
% observado. Por outro lado, o filtro de Blackman-Harris proporciona uma estimativa um pouco melhor do 
% ruído branco de fundo, uma vez que esse espectro de fundo apresenta-se mais suavizado do que nos outros 
% dois casos. Embora a suavização — ou a média — das frequências adjacentes promovida pela janela de 
% Blackman-Harris possa parecer uma desvantagem nesta situação, ela pode ser benéfica ao lidar com dados 
% reais, nos quais o espectro pode apresentar alta variabilidade. Se o conjunto de dados for suficientemente 
% extenso (por exemplo, 256 pontos ou mais), as vantagens de se utilizar uma janela não retangular tornam-se 
% pouco expressivas. 
